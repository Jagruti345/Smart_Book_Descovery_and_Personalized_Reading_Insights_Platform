def run():
    print("Clearing database and replacing dummy books with real world literature...")
    # Clean previous books and dummy ratings
    db.query(Rating).delete()
    db.query(ReadingHistory).delete()
    db.query(UserBadge).delete()
    db.query(Book).delete()
    db.commit()

    # Insert real books
    inserted_books = []
    for b in REAL_BOOKS:
        book_obj = Book(**b)
        db.add(book_obj)
        inserted_books.append(book_obj)
    db.commit()
    print(f"Successfully seeded {len(inserted_books)} real literary masterworks!")

    # Setup demo user
    demo = db.query(User).filter(User.email == "demo@bookapp.dev").first()
    if not demo:
        demo = User(
            name="Elena Vance",
            email="demo@bookapp.dev",
            hashed_password=hash_password("demo1234"),
            role="admin",
            onboarding_complete=True,
            current_streak=5,
            longest_streak=12,
            total_minutes_read=480,
            preferences={
                "reading_frequency": "regular",
                "daily_minutes_goal": 25,
                "favorite_genres": ["Mystery", "Classic", "Philosophy"],
                "loved_books_or_authors": ["Arthur Conan Doyle", "Marcus Aurelius", "Jane Austen"],
                "preferred_format": "both",
                "primary_purpose": "pleasure",
            },
        )
        db.add(demo)
        db.commit()
        db.refresh(demo)
    else:
        demo.name = "Elena Vance"
        demo.current_streak = 5
        demo.longest_streak = 12
        demo.total_minutes_read = 480
        demo.preferences = {
            "reading_frequency": "regular",
            "daily_minutes_goal": 25,
            "favorite_genres": ["Mystery", "Classic", "Philosophy"],
            "loved_books_or_authors": ["Arthur Conan Doyle", "Marcus Aurelius", "Jane Austen"],
            "preferred_format": "both",
            "primary_purpose": "pleasure",
        }
        db.commit()

    # Seed ratings for demo user
    rng = random.Random(42)
    all_books = db.query(Book).all()
    for b in all_books:
        if any(g in ["Mystery", "Classic", "Philosophy"] for g in (b.genres or [])):
            if rng.random() < 0.6:
                stars = 4.0 if rng.random() < 0.5 else 5.0
                db.add(Rating(user_id=demo.id, book_id=b.id, stars=stars))
        elif rng.random() < 0.2:
            db.add(Rating(user_id=demo.id, book_id=b.id, stars=3.0))
    db.commit()

    # Seed some reading history for rich dashboard telemetry
    from datetime import datetime, timezone, timedelta
    now = datetime.now(timezone.utc)
    dates = [(now - timedelta(days=i)).strftime("%Y-%m-%d") for i in range(7)]
    minutes_samples = [35, 25, 40, 20, 45, 30, 25]

    for i, date_str in enumerate(dates):
        # Pick a book related to preferences
        book_match = next((b for b in all_books if "Mystery" in b.genres or "Philosophy" in b.genres), all_books[0])
        mode = "audio" if i % 3 == 0 else "text"
        db.add(ReadingHistory(
            user_id=demo.id,
            book_id=book_match.id,
            minutes=minutes_samples[i],
            mode=mode,
            progress_percent=min(100.0, 15.0 * (i + 1)),
            session_date=date_str,
            started_at_hour=21 if i % 2 == 0 else 14,
        ))
    db.commit()

    # Seed badges
    db.add(UserBadge(user_id=demo.id, badge_code="first_chapter"))
    db.add(UserBadge(user_id=demo.id, badge_code="night_owl"))
    db.add(UserBadge(user_id=demo.id, badge_code="genre_explorer"))
    db.commit()

    print("Demo reader and rich telemetry data initialized successfully!")
    db.close()


if __name__ == "__main__":
    run()
